// QR codes generated by the app encode full URLs, e.g.
// "https://inventory.reethau.id/asset/{sku}" or ".../site/{siteId}".
// A raw barcode/SKU label, on the other hand, is just the plain code.
// This extracts the actual searchable term so a scanned/typed/pasted value
// behaves the same as typing the SKU / site name manually — used both for
// the camera scanner and for hardware "keyboard-wedge" barcode scanners
// (which type straight into the focused search field) or manual paste.
function parseScanCode(raw: string): { term: string; site?: SiteLocation } {
  const trimmed = raw.trim();
  try {
    const url = new URL(trimmed);
    const parts = url.pathname.split('/').filter(Boolean); // e.g. ['site','bekasi'] or ['asset','SKU-1']
    if (parts.length >= 2 && parts[0] === 'site') {
      const siteId = parts[1].toLowerCase() as SiteLocation;
      if (siteId in SITE_LABEL) {
        return { term: SITE_LABEL[siteId], site: siteId };
      }
      return { term: decodeURIComponent(parts[1]) };
    }
    if (parts.length >= 2 && parts[0] === 'asset') {
      return { term: decodeURIComponent(parts[1]) };
    }
    if (parts.length > 0) {
      return { term: decodeURIComponent(parts[parts.length - 1]) };
    }
    return { term: trimmed };
  } catch {
    // Not a URL — treat the scanned value as a plain SKU/barcode.
    return { term: trimmed };
  }
}

